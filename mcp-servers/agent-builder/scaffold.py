"""
StackVend agent-builder: safe ADK scaffold rendering (lane 14 PR-1, FD27-12).

Every caller-supplied value reaches generated Python only through `repr()` of a str/int (a literal), never by text
substitution; tool names are validated identifiers (validator.validate_tool_matrix). Each rendered `.py` file is
`ast.parse`d and its AST shape (node types and identifiers, constants blanked) must equal the shape of the same
template rendered with neutral values: an injected value that changed the program's structure is refused.

The MCP server never imports or executes these files (PR-9 packages them inside the child project's Cloud Build).
"""

from __future__ import annotations

import ast
from dataclasses import dataclass, replace
from typing import Dict, List, Tuple

SAFETY_DELIMITERS = ("<retrieved_context>", "</retrieved_context>")


@dataclass(frozen=True)
class ScaffoldParams:
    agent_name: str
    model_name: str
    system_instruction: str
    grounding_datastore_id: str
    max_turns: int
    per_request_timeout_seconds: int
    read_tools: Tuple[str, ...]
    action_tools: Tuple[str, ...]


def _py_identifier(agent_name: str) -> str:
    """ADK agent names must be identifiers; the normalized agent name only holds [a-z0-9_-]."""
    ident = agent_name.replace("-", "_")
    return ident if ident.isidentifier() else f"agent_{ident}"


def render_app(p: ScaffoldParams) -> str:
    return (
        '"""Generated by StackVend agent-builder: runtime limits for the ADK agent."""\n'
        "\n"
        f"AGENT_NAME = {p.agent_name!r}\n"
        f"MODEL_NAME = {p.model_name!r}\n"
        f"MAX_TURNS = {int(p.max_turns)!r}\n"
        f"PER_REQUEST_TIMEOUT_SECONDS = {int(p.per_request_timeout_seconds)!r}\n"
        "\n"
        "\n"
        "def runtime_limits():\n"
        '    return {"max_turns": MAX_TURNS, "per_request_timeout_seconds": PER_REQUEST_TIMEOUT_SECONDS}\n'
    )


def render_agent(p: ScaffoldParams) -> str:
    tool_refs = [f"read_tools.{n}" for n in p.read_tools] + [f"action_tools.{n}" for n in p.action_tools]
    return (
        '"""Generated by StackVend agent-builder: ADK agent definition."""\n'
        "\n"
        f"SYSTEM_INSTRUCTION = {p.system_instruction!r}\n"
        f"AGENT_NAME = {p.agent_name!r}\n"
        f"ADK_AGENT_NAME = {_py_identifier(p.agent_name)!r}\n"
        f"MODEL_NAME = {p.model_name!r}\n"
        f"GROUNDING_DATASTORE_ID = {p.grounding_datastore_id!r}\n"
        f"SAFETY_DELIMITERS = {SAFETY_DELIMITERS!r}\n"
        "\n"
        "\n"
        "def get_agent_config():\n"
        "    return {\n"
        '        "name": AGENT_NAME,\n'
        '        "model": MODEL_NAME,\n'
        '        "instruction": SYSTEM_INSTRUCTION,\n'
        '        "grounding_datastore_id": GROUNDING_DATASTORE_ID,\n'
        '        "safety_delimiters": list(SAFETY_DELIMITERS),\n'
        "    }\n"
        "\n"
        "\n"
        "def build_root_agent():\n"
        '    """The ADK agent. Imported only inside the child project\'s packaging build, never by the platform."""\n'
        "    from google.adk.agents import Agent\n"
        "\n"
        "    from tools import action_tools, read_tools\n"
        "\n"
        "    return Agent(\n"
        "        name=ADK_AGENT_NAME,\n"
        "        model=MODEL_NAME,\n"
        "        instruction=SYSTEM_INSTRUCTION,\n"
        f"        tools=[{', '.join(tool_refs)}],\n"
        "    )\n"
    )


def render_read_tools(p: ScaffoldParams) -> str:
    out = ['"""Read-only tools (generated stubs: implement the data access before deploying)."""',
           "from typing import Any, Dict", ""]
    if not p.read_tools:
        out.append("# No read-only tools configured")
    for name in p.read_tools:
        out += ["", f"def {name}(**kwargs) -> Dict[str, Any]:",
                '    """Read-only tool."""',
                f'    return {{"status": "NOT_IMPLEMENTED", "tool": {name!r}, "arguments": kwargs}}', ""]
    return "\n".join(out) + "\n"


def render_action_tools(p: ScaffoldParams) -> str:
    out = ['"""State-mutating tools: every call needs an operator confirmation token."""',
           "from typing import Any, Dict", "", "",
           "def require_confirmation(func):",
           "    def wrapper(*args, **kwargs):",
           '        if not kwargs.get("confirmation_token"):',
           "            return {",
           '                "status": "APPROVAL_REQUIRED",',
           '                "action": func.__name__,',
           '                "message": "State-mutating operation requires confirmed operator token.",',
           "            }",
           "        return func(*args, **kwargs)",
           "    wrapper.__name__ = func.__name__",
           "    return wrapper", ""]
    if not p.action_tools:
        out.append("# No state-mutating tools configured")
    for name in p.action_tools:
        out += ["", "@require_confirmation", f"def {name}(**kwargs) -> Dict[str, Any]:",
                '    """State-mutating tool requiring confirmation."""',
                f'    return {{"status": "NOT_IMPLEMENTED", "tool": {name!r}, "arguments": kwargs}}', ""]
    return "\n".join(out) + "\n"


def render_test(p: ScaffoldParams) -> str:
    return (
        '"""Generated unit test: runtime limits and agent configuration."""\n'
        "import unittest\n"
        "\n"
        "from agent import get_agent_config\n"
        "from app import runtime_limits\n"
        "\n"
        "\n"
        "class TestAgentConfig(unittest.TestCase):\n"
        "    def test_limits(self):\n"
        f"        self.assertEqual(runtime_limits()[\"max_turns\"], {int(p.max_turns)!r})\n"
        "\n"
        "    def test_config(self):\n"
        f"        self.assertEqual(get_agent_config()[\"name\"], {p.agent_name!r})\n"
        "\n"
        "\n"
        'if __name__ == "__main__":\n'
        "    unittest.main()\n"
    )


def render_deploy_note(p: ScaffoldParams) -> str:
    return (
        '"""Deployment is done by the StackVend platform (agent-builder `agent_engine_deploy`, an approved operator\n'
        "action): it packages this directory in a Cloud Build inside the workload's own project. This file deploys\n"
        'nothing and reports nothing."""\n'
        "\n"
        "\n"
        "def deploy():\n"
        '    raise SystemExit("Deploy through the StackVend agent-builder agent_engine_deploy tool (approval required).")\n'
        "\n"
        "\n"
        'if __name__ == "__main__":\n'
        "    deploy()\n"
    )


REQUIREMENTS = (
    "google-adk>=0.1.0",
    "google-cloud-aiplatform>=1.49.0",
    "google-cloud-firestore>=2.15.0",
    "pydantic>=2.0.0",
    "httpx>=0.27.0",
    "pytest>=8.0.0",
)

PY_RENDERERS = {
    "app.py": render_app,
    "agent.py": render_agent,
    "tools/read_tools.py": render_read_tools,
    "tools/action_tools.py": render_action_tools,
    "tests/test_agent.py": render_test,
    "deploy.py": render_deploy_note,
}


def _neutral(p: ScaffoldParams) -> ScaffoldParams:
    return replace(p, agent_name="agent", model_name="model", system_instruction="instruction",
                   grounding_datastore_id="", max_turns=1, per_request_timeout_seconds=1)


class _BlankConstants(ast.NodeTransformer):
    def visit_Constant(self, node: ast.Constant):  # noqa: N802 (ast API)
        return ast.copy_location(ast.Constant(value=type(node.value).__name__), node)


def ast_shape(source: str) -> str:
    """AST dump with every constant replaced by its type name: identical for any literal values."""
    tree = _BlankConstants().visit(ast.parse(source))
    return ast.dump(tree, include_attributes=False)


_RESERVED_NAMES: Tuple[str, ...] = ()


def reserved_names() -> frozenset:
    """RT F6: every name the templates themselves bind or reference (functions, classes, arguments, assignment
    targets, imported names and modules, loaded names), taken from the AST of a neutral render with no tools. A tool
    named like one of them would rebind it (e.g. `require_confirmation` turns the next action tool into a dict), so
    such a tool name is refused. Exact set from the real parser, never a pattern."""
    global _RESERVED_NAMES
    if not _RESERVED_NAMES:
        base = ScaffoldParams(agent_name="agent", model_name="model", system_instruction="instruction",
                              grounding_datastore_id="", max_turns=1, per_request_timeout_seconds=1,
                              read_tools=(), action_tools=())
        names = set()
        for render in PY_RENDERERS.values():
            for node in ast.walk(ast.parse(render(base))):
                if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                    names.add(node.name)
                elif isinstance(node, ast.arg):
                    names.add(node.arg)
                elif isinstance(node, ast.Name):
                    names.add(node.id)
                elif isinstance(node, ast.alias):
                    names.add(node.asname or node.name.split(".")[0])
                elif isinstance(node, ast.ImportFrom) and node.module:
                    names.add(node.module.split(".")[0])
        _RESERVED_NAMES = tuple(sorted(names))
    return frozenset(_RESERVED_NAMES)


def render_files(p: ScaffoldParams) -> Tuple[Dict[str, str], List[str]]:
    """(files, violations). A violation means a rendered file failed to parse or changed shape."""
    neutral = _neutral(p)
    files: Dict[str, str] = {}
    violations: List[str] = []
    for fname, render in PY_RENDERERS.items():
        src = render(p)
        try:
            if ast_shape(src) != ast_shape(render(neutral)):
                violations.append(f"{fname}: rendered structure differs from the template")
        except SyntaxError as e:
            violations.append(f"{fname}: rendered file does not parse ({e.msg})")
        files[fname] = src
    files["tools/__init__.py"] = ""
    files["requirements.txt"] = "\n".join(REQUIREMENTS) + "\n"
    return files, violations
