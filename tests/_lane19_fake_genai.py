# A small, valid FastAPI + Firestore workload (what the deleted template used to provide for these tests).
FASTAPI_MAIN = '''import os

from fastapi import FastAPI

app = FastAPI(title="workload")


@app.get("/health")
def health_check():
    return {"status": "healthy"}


@app.get("/api/config")
def config():
    return {"project": os.environ.get("PROJECT_ID", "")}
'''


def canned_workload_files(product_id: str, extra: Optional[Dict[str, str]] = None) -> Dict[str, str]:
    svc = product_id.lower().replace("_", "-")
    files = {
        f"apps/{svc}/main.py": FASTAPI_MAIN,
        f"apps/{svc}/requirements.txt": "fastapi>=0.110.0\nuvicorn>=0.28.0\ngoogle-cloud-firestore>=2.16.0\n",
        f"apps/{svc}/Procfile": "web: uvicorn main:app --host 0.0.0.0 --port $PORT\n",
        f"apps/{svc}/.python-version": "3.12\n",
        f"tests/test_{svc.replace('-', '_')}.py": (
            "def test_placeholder():\n    assert True\n"
        ),
    }
    files.update(extra or {})
    return files


class FakeModels:
    def __init__(self, payloads: List[str]):
        self._payloads = list(payloads)
        self.calls: List[Dict] = []

    def generate_content(self, model=None, contents=None, config=None):
        self.calls.append({"model": model, "contents": contents})
        text = self._payloads[min(len(self.calls) - 1, len(self._payloads) - 1)]
        return SimpleNamespace(text=text, candidates=[], usage_metadata=None)


class FakeGenaiClient:
    """``client.models.generate_content(...)`` returns each payload in turn (the last one repeats)."""

    def __init__(self, files: Optional[Dict[str, str]] = None, payloads: Optional[List[str]] = None):
        if payloads is None:
            payloads = [json.dumps({"files": dict(files or {})})]
        self.models = FakeModels(payloads)


def async_assigned_files_fake(paths: List[str], body: str = "# generated by fake junior\n"):
    """Async stand-in for ``SwarmDispatcher._call_gemini_with_backoff``: returns the given paths that the junior's
    prompt names (the prompt lists the task's assigned files), plus a token count."""
    async def _fake(prompt, system_instruction, model_name, trace_id=None):
        return {p: body for p in paths if p in prompt}, 100
    return _fake
