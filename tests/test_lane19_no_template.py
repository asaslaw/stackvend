def _swarm_env(enabled: bool):
    return patch.dict(os.environ, {"ENABLE_DEVELOPER_SWARM": "true" if enabled else "false"})


def _plan():
    return LeadDeveloperDecompositionPlan(
        execution_mode=SwarmExecutionMode.STANDARD_SWARM, iac_engine="OPENTOFU", vcs_provider="GITHUB",
        tasks=[JuniorTaskAssignment(task_id="t1", persona=JuniorPersona.BACKEND_ENGINEER, wave=1,
                                    assigned_files=["apps/a/main.py"], task_objective="x")])


def _run(agent, **kw):
    # FD-4R R-6: the developer requires the compliance decision (no keyword / default fallback); a plain public one.
    kw = {"allow_unauthenticated": True, "enable_direct_iap": False, "domain_restricted_sharing": False, **kw}
    with patch.object(agent, "fetch_existing_repo_files", return_value={}), \
            patch.object(agent, "update_build_step_status") as marks, \
            patch.object(H, "get_model_cascade_for_agent", return_value=["model-a", "model-b"]), \
            patch.object(H, "wait_for_rate_limit_cooldown", return_value=True):
        try:
            return agent.generate_code_files(product_id="noapp", spec_text="An app", task_dag=[], **kw), marks
        except DeveloperStageError as e:
            e.marks = marks
            raise


