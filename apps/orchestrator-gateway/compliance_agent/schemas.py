"""
Pydantic schemas for the Compliance Agent with fallback support.
"""

from typing import Any, Dict, List, Optional

from . import profiles as _profiles

try:
    from pydantic import BaseModel, Field
except ImportError:
    class BaseModel:
        def __init__(self, **kwargs):
            for k, v in kwargs.items():
                setattr(self, k, v)
        def dict(self):
            return self.__dict__
    def Field(*args, **kwargs):
        return kwargs.get("default", None)


class ComplianceAuditRequest(BaseModel):
    product_id: str = Field(default="", description="Product identifier e.g. castorcloudruntest")
    spec_text: str = Field(default="", description="Original requirements specification")
    task_dag: List[Dict[str, Any]] = Field(default_factory=list, description="Initial task DAG generated by Architect Agent")
    folder_id: Optional[str] = Field(default="", description="Target parent GCP Folder ID")
    trace_id: Optional[str] = Field(default=None, description="Pipeline trace ID")
    plan_markdown: Optional[str] = Field(default=None, description="Implementation plan markdown from Architect Agent")
    plan_file_path: Optional[str] = Field(default=None, description="Repository target path for implementation plan")
    policy_matrix: Optional[Dict[str, Any]] = Field(default=None, description="Tier 1 Org Policy intent matrix")
    # compliance-profile-explicit: the explicit, typed profile selection (compliance_agent/profiles.py), validated by
    # the caller (the gateway route answers 422 for anything outside the exact vocabulary). None = no selection.
    compliance_profile: Optional[str] = Field(default=None, description="Explicit compliance profile selection")
    # Where the selection came from: EXPLICIT_REQUEST (this run) or WORKLOAD_SELECTION (stored on the workload).
    compliance_profile_origin: Optional[str] = Field(default=None, description="Origin of the explicit selection")


class ComplianceAuditResponse(BaseModel):
    product_id: str = Field(default="")
    compliance_profile: Optional[str] = Field(default="STANDARD")
    is_regulated: bool = Field(default=False)
    requires_cmek: bool = Field(default=False)
    requires_audit_logging: bool = Field(default=False)
    domain_restricted_sharing: bool = Field(default=False)
    allowed_domains: List[str] = Field(default_factory=list)
    allow_unauthenticated: bool = Field(default=True)
    enable_direct_iap: bool = Field(default=False)
    enforce_private_ingress: bool = Field(default=False)
    enriched_dag: List[Dict[str, Any]] = Field(default_factory=list)
    injected_tasks: List[Dict[str, Any]] = Field(default_factory=list)
    compliance_summary: str = Field(default="")
    status: str = Field(default="PASSED")
    plan_markdown: Optional[str] = Field(default=None, description="Enriched implementation plan markdown")
    plan_file_path: Optional[str] = Field(default=None, description="Repository target path for implementation plan")
    policy_matrix: Optional[Dict[str, Any]] = Field(default=None, description="Org Policy intent matrix evaluated against")
    has_policy_conflicts: bool = Field(default=False, description="Whether policy conflicts or rewrites were detected")
    policy_conflicts: List[str] = Field(default_factory=list, description="List of detected policy conflict descriptions")
    requires_human_approval: bool = Field(default=False, description="Whether human approval is required based on governance policy")
    # compliance-profile-explicit: where the profile came from, and advisory notes that never change it.
    compliance_profile_source: Optional[str] = Field(default=None, description="EXPLICIT_REQUEST / WORKLOAD_SELECTION / ASSURED_WORKLOADS_FOLDER / DEFAULT_STANDARD")
    profile_advisories: List[Dict[str, Any]] = Field(default_factory=list, description="Advisory profile suggestions (never applied)")
    # ACCESS-INTERNAL-SERVICE-ADVISORY: `ACCESS.INTERNAL_SERVICE_PUBLIC` per Cloud Run push target of a Public app
    # (compliance_agent/access_advisory.py). Non-empty: the run waits for plan approval and the card shows it.
    access_advisories: List[Dict[str, Any]] = Field(default_factory=list, description="Typed access warnings (plan approval)")
    access_advisories_omitted: int = Field(default=0, ge=0, description="Advisories beyond the first 50, counted only")



# ------------------------------------------------------------------------------------------------------------------
# Lane 17 PR-1a (compliance bundle, owner 10-12): the compliance server's `/inspect-folder` answer, contract v2.
# The gateway validates every answer against this before using it; any mismatch is COMPLIANCE_UNAVAILABLE (fail
# closed), never a STANDARD / public default. Extra fields are allowed (the server sends the full org-policy matrix).
# Validation only: the handler keeps using the server's own JSON object, so a valid answer is enriched exactly as
# before (tests/test_compliance_bundle.py golden check).
# ------------------------------------------------------------------------------------------------------------------
# v3 (compliance-profile-explicit): the profile comes from the explicit request or the folder regime, never spec
# keywords; `profile_source` / `requested_profile` / `profile_suggestions` are required. A v2 server would ignore the
# explicit profile and guess from spec words, so it is refused (fail closed).
REQUIRED_COMPLIANCE_CONTRACT_VERSION = 3
DIRECT_IAP_STEP_ID = "STEP-03D-DIRECT-IAP"
PRIVATE_INGRESS_STEP_IDS = ("STEP-06B-SERVERLESS-NEG", "STEP-06C-HTTPS-LOAD-BALANCER")

try:
    from pydantic import ConfigDict, StrictBool, StrictInt, StrictStr, model_validator

    class RemoteMandatedTask(BaseModel):
        model_config = ConfigDict(extra="allow")
        step_id: StrictStr = Field(min_length=1)
        title: StrictStr

    class RemoteInspectResponseV2(BaseModel):
        model_config = ConfigDict(extra="allow")

        contract_version: StrictInt
        intent_source: StrictStr
        profile: StrictStr = Field(min_length=1)
        profile_source: StrictStr
        requested_profile: Optional[StrictStr]
        profile_suggestions: List[Dict[str, Any]]
        is_regulated: StrictBool
        requires_cmek: StrictBool
        requires_audit_logging: StrictBool
        domain_restricted_sharing: StrictBool
        allowed_domains: List[StrictStr]
        allow_unauthenticated: StrictBool
        enable_direct_iap: StrictBool
        enforce_private_ingress: StrictBool
        mandated_tasks: List[RemoteMandatedTask]
        policy_matrix: Dict[str, Any]

        @model_validator(mode="after")
        def _contract_invariants(self):
            if self.contract_version < REQUIRED_COMPLIANCE_CONTRACT_VERSION:
                raise ValueError(
                    f"contract_version {self.contract_version} < {REQUIRED_COMPLIANCE_CONTRACT_VERSION} "
                    f"(compliance server older than the gateway)"
                )
            if self.profile not in _profiles.KNOWN_PROFILES:
                raise ValueError(f"profile {self.profile!r} is not a known compliance profile")
            if self.profile_source not in _profiles.SERVER_PROFILE_SOURCES:
                raise ValueError(f"profile_source {self.profile_source!r} is not one of "
                                 f"{sorted(_profiles.SERVER_PROFILE_SOURCES)}")
            if self.requested_profile is not None and self.requested_profile not in _profiles.KNOWN_PROFILES:
                raise ValueError(f"requested_profile {self.requested_profile!r} is not a known compliance profile")
            if self.profile_source == _profiles.SOURCE_EXPLICIT_REQUEST and self.profile != self.requested_profile:
                raise ValueError("profile_source EXPLICIT_REQUEST with a profile different from requested_profile")
            if self.profile_source == _profiles.SOURCE_DEFAULT and (
                    self.profile != "STANDARD" or self.requested_profile is not None):
                raise ValueError("profile_source DEFAULT_STANDARD needs profile STANDARD and no requested_profile")
            # The ingress decision must be internally consistent: an IAP / domain-restricted answer can never be
            # public, and a private answer can never take the gateway's STANDARD fast path (which answers public).
            if self.enable_direct_iap and self.allow_unauthenticated:
                raise ValueError("enable_direct_iap=true with allow_unauthenticated=true")
            if self.domain_restricted_sharing and self.allow_unauthenticated:
                raise ValueError("domain_restricted_sharing=true with allow_unauthenticated=true")
            if not self.allow_unauthenticated and not self.is_regulated:
                raise ValueError("allow_unauthenticated=false with is_regulated=false")
            if (self.enable_direct_iap or self.enforce_private_ingress) and not self.is_regulated:
                raise ValueError("an IAP / private-ingress answer with is_regulated=false")
            step_ids = {t.step_id for t in self.mandated_tasks}
            if self.enable_direct_iap and DIRECT_IAP_STEP_ID not in step_ids:
                raise ValueError(f"enable_direct_iap=true without mandated task {DIRECT_IAP_STEP_ID}")
            if self.enforce_private_ingress and not set(PRIVATE_INGRESS_STEP_IDS) <= step_ids:
                raise ValueError(f"enforce_private_ingress=true without mandated tasks {list(PRIVATE_INGRESS_STEP_IDS)}")
            return self
except ImportError:  # pragma: no cover - pydantic is a hard requirement of the gateway
    RemoteInspectResponseV2 = None
